"""data/processed/build_report.md and docs/img/criteria_distribution.png (phase 6).

The report is regenerated by every build: counts, completeness, confidence, the shoes we
trust least, distributions, automatic flags and a sanity table of well-known shoes.
Hand-written comments belong in docs/reports/phase-6.md, not here.
"""

from collections import Counter
from pathlib import Path

import matplotlib

matplotlib.use("Agg")  # no window: the build runs in a terminal
import matplotlib.pyplot as plt
from matplotlib.ticker import MaxNLocator

from pipeline.models import Criterion, Specs, TerrainScores

ROOT = Path(__file__).resolve().parents[2]
REPORT_PATH = ROOT / "data" / "processed" / "build_report.md"
COVERAGE_PATH = ROOT / "docs" / "data-coverage.md"
COVERAGE_START, COVERAGE_END = "<!-- build:start -->", "<!-- build:end -->"
IMG_DIR = ROOT / "docs" / "img"
PLOT_NAME = "criteria_distribution.png"
CRITERIA = [c.value for c in Criterion]
LEVEL_ORDER = {"low": 0, "medium": 1, "high": 2}
# A spec and an expert sub-score this far apart on the same criterion are worth a look.
DISAGREEMENT = 4.0
# Chart colours: one series, so one hue (dataviz reference palette, light surface).
SURFACE, INK, INK_SECONDARY, GRID, BAR = "#fcfcfb", "#0b0b0b", "#52514e", "#e4e3df", "#2a78d6"

# Well-known shoes and what a runner would expect from them. These expectations are
# general running knowledge written by the project, NOT data: they are only a yardstick.
SANITY = {
    "brooks-cascadia-20": "stable, protective, well cushioned, rather heavy",
    "saucony-peregrine-15": "all-rounder, very good grip, fairly light",
    "la-sportiva-bushido-3": "firm and stable, protective, grippy, snug fit",
    "la-sportiva-prodigio-max": "max cushion, protective, stable",
    "merrell-mtl-adapt-matryx": "max cushion, protective, durable, heavy",
    "asics-trabuco-max-4": "max cushion, heavy, not very responsive",
    "altra-lone-peak-9": "wide toe box, moderate cushion",
    "nnormal-kjerag": "light racer, little cushion, responsive",
    "inov-8-mudtalon-speed-2": "mud shoe: deep lugs, top grip, little cushion",
    "vibram-fivefingers-v-tr-2": "barefoot: no cushioning, very light, low and stable",
}


def _pct(part: int, whole: int) -> str:
    return f"{part} ({part / whole:.0%})" if whole else "0"


def _score(value: float | None) -> str:
    return "-" if value is None else f"{value:.1f}"


def completeness_table(shoes: list[dict]) -> list[str]:
    """Known values per spec field, and from which tier."""
    n = len(shoes)
    lines = [
        "| Field | Known | Manufacturer | Lab (RunRepeat) | Retailer |",
        "|---|---|---|---|---|",
    ]
    for field in Specs.model_fields:
        if field == "sources":
            continue
        tiers = Counter(s["specs"]["sources"].get(field) for s in shoes)
        known = n - tiers[None]
        lines.append(
            f"| {field} | {_pct(known, n)} | {tiers['manufacturer']} "
            f"| {tiers['lab_measurement']} | {tiers['retailer']} |"
        )
    return lines


def criteria_table(shoes: list[dict]) -> list[str]:
    """Scored shoes per criterion and what the scores rest on."""
    n = len(shoes)
    lines = [
        "| Criterion | Scored | Specs only | Reviews only | Both | Median |",
        "|---|---|---|---|---|---|",
    ]
    for criterion in CRITERIA:
        scores = [s["criteria_scores"][criterion] for s in shoes]
        known = [c for c in scores if c["score_0_10"] is not None]
        spec_only = sum(c["expert_score_0_10"] is None for c in known)
        expert_only = sum(c["spec_score_0_10"] is None for c in known)
        values = sorted(c["score_0_10"] for c in known)
        median = values[len(values) // 2] if values else None
        lines.append(
            f"| {criterion} | {_pct(len(known), n)} | {spec_only} | {expert_only} "
            f"| {len(known) - spec_only - expert_only} | {_score(median)} |"
        )
    return lines


def terrain_table(shoes: list[dict]) -> list[str]:
    """Scored shoes per terrain (lug depth is required)."""
    n = len(shoes)
    lines = ["| Terrain | Scored |", "|---|---|"]
    for terrain in TerrainScores.model_fields:
        known = sum(s["terrain_scores"][terrain]["score_0_10"] is not None for s in shoes)
        lines.append(f"| {terrain} | {_pct(known, n)} |")
    return lines


def lowest_confidence(shoes: list[dict], count: int = 10) -> list[str]:
    """The shoes we trust least: level, then completeness, then evidence."""
    ranked = sorted(
        shoes,
        key=lambda s: (
            LEVEL_ORDER[s["confidence"]["level"]],
            s["confidence"]["spec_completeness_0_1"],
            s["confidence"]["expert_review_count"],
            s["confidence"]["buyer_review_count"],
            s["id"],
        ),
    )[:count]
    lines = [
        "| Shoe | Level | Spec completeness | Expert reviews | Buyer reviews | Criteria scored |",
        "|---|---|---|---|---|---|",
    ]
    for shoe in ranked:
        conf = shoe["confidence"]
        scored = sum(shoe["criteria_scores"][c]["score_0_10"] is not None for c in CRITERIA)
        lines.append(
            f"| {shoe['id']} | {conf['level']} | {conf['spec_completeness_0_1']:.0%} "
            f"| {conf['expert_review_count']} | {conf['buyer_review_count']} | {scored}/8 |"
        )
    return lines


def disagreements(shoes: list[dict]) -> list[str]:
    """Criteria where the spec and expert sub-scores are far apart (automatic flag)."""
    rows = []
    for shoe in shoes:
        for criterion in CRITERIA:
            score = shoe["criteria_scores"][criterion]
            spec, expert = score["spec_score_0_10"], score["expert_score_0_10"]
            if spec is not None and expert is not None and abs(spec - expert) >= DISAGREEMENT:
                rows.append((abs(spec - expert), shoe["id"], criterion, spec, expert))
    lines = ["| Shoe | Criterion | Spec sub-score | Expert sub-score |", "|---|---|---|---|"]
    lines += [f"| {i} | {c} | {s:.1f} | {e:.1f} |" for _, i, c, s, e in sorted(rows, reverse=True)]
    return lines if rows else ["None."]


def sanity_table(shoes: list[dict]) -> list[str]:
    """Scores of well-known shoes next to what one would expect of them."""
    by_id = {s["id"]: s for s in shoes}
    short = ["cush", "prot", "grip", "stab", "resp", "light", "dura", "fit"]
    lines = [
        "| Shoe | Expected (general knowledge) | " + " | ".join(short) + " | Confidence |",
        "|---|---|" + "---|" * len(short) + "---|",
    ]
    for shoe_id, expected in SANITY.items():
        shoe = by_id.get(shoe_id)
        if shoe is None:
            lines.append(f"| {shoe_id} | {expected} | not in catalogue |" + " |" * len(short))
            continue
        scores = " | ".join(_score(shoe["criteria_scores"][c]["score_0_10"]) for c in CRITERIA)
        lines.append(f"| {shoe_id} | {expected} | {scores} | {shoe['confidence']['level']} |")
    return lines


def plot_distributions(shoes: list[dict], path: Path) -> None:
    """Small multiples: histogram of each criterion score (0-10) over the catalogue."""
    fig, axes = plt.subplots(2, 4, figsize=(12, 5.4), sharex=True, facecolor=SURFACE)
    for ax, criterion in zip(axes.flat, CRITERIA, strict=True):
        values = [
            s["criteria_scores"][criterion]["score_0_10"]
            for s in shoes
            if s["criteria_scores"][criterion]["score_0_10"] is not None
        ]
        ax.set_facecolor(SURFACE)
        # Thin bars with a surface-coloured edge: a visible gap between adjacent bins.
        ax.hist(values, bins=range(11), color=BAR, edgecolor=SURFACE, linewidth=2)
        ax.set_title(
            f"{criterion.replace('_', ' ')}  ·  {len(values)} of {len(shoes)} scored",
            fontsize=10,
            color=INK,
            loc="left",
        )
        ax.set_xlim(0, 10)
        ax.set_xticks(range(0, 11, 2))
        ax.yaxis.set_major_locator(MaxNLocator(integer=True))  # counts of shoes
        ax.grid(axis="y", color=GRID, linewidth=0.8)
        ax.set_axisbelow(True)
        for side in ("top", "right", "left"):
            ax.spines[side].set_visible(False)
        ax.spines["bottom"].set_color(GRID)
        ax.tick_params(colors=INK_SECONDARY, labelsize=8, length=0)
    for ax in axes[1]:
        ax.set_xlabel("score (0-10)", fontsize=9, color=INK_SECONDARY)
    for ax in axes[:, 0]:
        ax.set_ylabel("shoes", fontsize=9, color=INK_SECONDARY)
    fig.suptitle(
        "Criterion scores across the catalogue (shoes without a score are not shown)",
        fontsize=11,
        color=INK,
        x=0.01,
        ha="left",
    )
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=150, facecolor=SURFACE)
    plt.close(fig)


def write_coverage_block(shoes: list[dict], meta: dict) -> None:
    """Insert or replace the final-coverage block of docs/data-coverage.md."""
    block = "\n".join([
        COVERAGE_START,
        "",
        "## Final coverage in data/processed/shoes.json (phase 6)",
        "",
        f"Generated {meta['build_date']} by `python -m pipeline.build` (scoring "
        f"{meta['scoring_config_version']}): {len(shoes)} shoes. Each spec field takes the "
        "manufacturer value, else a lab measurement (RunRepeat), else the retailer's.",
        "",
        *completeness_table(shoes),
        "",
        *criteria_table(shoes),
        "",
        *terrain_table(shoes),
        "",
        COVERAGE_END,
    ])  # fmt: skip
    text = COVERAGE_PATH.read_text(encoding="utf-8") if COVERAGE_PATH.exists() else ""
    start, end = text.find(COVERAGE_START), text.find(COVERAGE_END)
    if start >= 0 and end > start:
        text = text[:start] + block + text[end + len(COVERAGE_END) :]
    else:
        text = text.rstrip() + "\n\n" + block + "\n"
    COVERAGE_PATH.write_text(text, encoding="utf-8")


def write_report(data: dict, meta: dict) -> None:
    """Write the build report and its plot."""
    shoes = data["shoes"]
    plot_distributions(shoes, IMG_DIR / PLOT_NAME)
    levels = Counter(s["confidence"]["level"] for s in shoes)
    reasons = Counter(
        reason.split(" (")[0] if "completeness" not in reason else "Spec completeness too low"
        for s in shoes
        for reason in s["confidence"]["reasons"]
    )
    dropped = meta["models_dropped"]
    lines = [
        "# Build report (generated by `python -m pipeline.build`)",
        "",
        f"Build date {meta['build_date']}, pipeline {meta['pipeline_version']}, "
        f"scoring.yaml {meta['scoring_config_version']}, aspects.yaml "
        f"{meta['aspects_config_version']}.",
        "",
        "## Counts",
        "",
        f"* Shoes in `shoes.json`: **{len(shoes)}** ({meta['brand_count']} brands, "
        f"{meta['offer_count']} retailer offers, {meta['expert_review_count']} expert reviews).",
        f"* Models dropped: {len(dropped)}"
        + ("" if not dropped else " — " + "; ".join(f"`{k}`: {v}" for k, v in dropped.items())),
        f"* Prices read between {meta['price_date_min']} and {meta['price_date_max']}.",
        "",
        "## Spec completeness per field",
        "",
        "Tier used for each known value (priority manufacturer > lab > retailer).",
        "",
        *completeness_table(shoes),
        "",
        "## Criterion scores",
        "",
        "A score needs a spec sub-score (enough spec inputs known) or at least one expert "
        "review that mentions the criterion; otherwise it is null.",
        "",
        *criteria_table(shoes),
        "",
        f"![Distribution of each criterion score](../../docs/img/{PLOT_NAME})",
        "",
        "## Terrain scores",
        "",
        *terrain_table(shoes),
        "",
        "## Confidence",
        "",
        "| Level | Shoes |",
        "|---|---|",
        *[f"| {level} | {levels[level]} |" for level in ("high", "medium", "low")],
        "",
        "Most frequent reasons a shoe is not one level higher:",
        "",
        *[f"* {reason}: {count} shoes" for reason, count in reasons.most_common(6)],
        "",
        "### The 10 shoes with the lowest confidence",
        "",
        *lowest_confidence(shoes),
        "",
        "## Automatic flag: specs and reviews disagree",
        "",
        f"Criteria whose spec and expert sub-scores differ by {DISAGREEMENT:g} points or more.",
        "",
        *disagreements(shoes),
        "",
        "## Sanity check: well-known shoes",
        "",
        "The *Expected* column is general running knowledge, not data. Judge whether the "
        "scores (0-10) agree; - means no score.",
        "",
        *sanity_table(shoes),
        "",
    ]
    REPORT_PATH.write_text("\n".join(lines), encoding="utf-8")
    write_coverage_block(shoes, meta)
